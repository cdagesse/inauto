export const MAKES: { name: string; slug: string; terms: string[] }[] = (() => {
  const seen = new Map<string, { name: string; slug: string; terms: Set<string> }>();
  for (const e of CATALOG) {
    const m = seen.get(e.makeSlug) ?? { name: e.make, slug: e.makeSlug, terms: new Set<string>() };
    for (const t of e.searchTerms) m.terms.add(t);
    seen.set(e.makeSlug, m);
  }
  return [...seen.values()].map((m) => ({ name: m.name, slug: m.slug, terms: [...m.terms] }));
})();

/** Lowercased, de-duplicated text the search index matches against. */
export function searchTextFor(e: CatalogEntry): string {
  const parts = [e.make, e.model, e.shortName ?? "", e.parentLine ?? "", ...e.searchTerms];
  return [...new Set(parts.map((p) => p.toLowerCase().trim()).filter(Boolean))].join(" ");
}
