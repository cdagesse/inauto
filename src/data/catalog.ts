/**
 * Hand-curated catalog of collector and enthusiast makes and models. This is
 * what search suggests and what an on-demand market report is built for.
 * Slugs are stable public URL segments: never rename one, add an alias instead.
 *
 * Visor aliases name the source's base model plus a trim pattern (ILIKE), because
 * Visor files "911 GT3 RS" as make=Porsche, model=911, trim="GT3 RS". Old Cars
 * Data aliases name the model as the auction titles spell it.
 */
export interface CatalogEntry {
  make: string;
  makeSlug: string;
  model: string;
  modelSlug: string;
  shortName?: string;
  parentLine?: string;
  yearStart: number;
  yearEnd: number | null;
  aliases: {
    visor: { make: string; model: string; trimPattern?: string };
    ocd: { make: string; model: string };
  };
  searchTerms: string[];
}

/** [model, yearStart, yearEnd, searchTerms?, visor?: {model, trim?}, shortName?, parentLine?, slug?] */
type M = [
  string,
  number,
  number | null,
  string[]?,
  { model: string; trim?: string }?,
  string?,
  string?,
  string?,
];

const slug = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

function make(
  name: string,
  models: M[],
  makeTerms: string[] = [],
  makeSlugOverride?: string,
): CatalogEntry[] {
  const makeSlug = makeSlugOverride ?? slug(name);
  return models.map(([model, y0, y1, terms = [], visor, shortName, parentLine, slugOverride]) => ({
    make: name,
    makeSlug,
    model,
    modelSlug: slugOverride ?? slug(model),
    shortName,
    parentLine: parentLine ?? name,
    yearStart: y0,
    yearEnd: y1,
    aliases: {
      visor: visor
        ? {
            make: name,
            model: visor.model,
            trimPattern: visor.trim ? `%${visor.trim}%` : undefined,
          }
        : { make: name, model },
      ocd: { make: name, model },
    },
    searchTerms: [...makeTerms, ...terms],
  }));
}

